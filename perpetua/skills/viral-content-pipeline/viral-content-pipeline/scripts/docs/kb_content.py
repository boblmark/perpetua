def g(dct_list, **kw):
    for d in dct_list:
        if all(d.get(k) == v for k, v in kw.items()):
            return d
    return None


def md(v, digits=2):
    if v is None:
        return "N/A"
    return f"{v:.{digits}f}%".replace(".00%", "%")


